  // 子的名稱（中文用棋子上的字；英文用通行的譯名）
  var PIECE_EN = { K: 'King', G: 'Advisor', M: 'Elephant', R: 'Chariot', N: 'Horse', C: 'Cannon', P: 'Soldier' };

  function detect() {
    var saved = readSettings().lang;
    if (saved !== 'zh-TW' && saved !== 'en') { try { saved = localStorage.getItem(LKEY); } catch (e) { saved = null; } }
    if (saved === 'zh-TW' || saved === 'en') return saved;
    var nav = (navigator.languages && navigator.languages[0]) || navigator.language || '';
    return /^zh/i.test(nav) ? 'zh-TW' : 'en';
  }
  var lang = detect();

  function raw(key) {
    var d = DICT[lang];
    if (d && Object.prototype.hasOwnProperty.call(d, key)) return d[key];
    if (Object.prototype.hasOwnProperty.call(DICT['zh-TW'], key)) return DICT['zh-TW'][key];
    return key;
  }
  function t(key, params) {
    var s = raw(key);
    if (!params) return s;
    return s.replace(/\{(\w+)\}/g, function (m, k) { return params[k] != null ? String(params[k]) : m; });
  }

  // 子的名稱：p 是引擎的代號（大寫紅、小寫黑）。中文直接用棋子上的字（帥／將…）；英文「Red Chariot」
  function pieceName(p, names) {
    if (lang === 'en') return t('piece.full', { color: t(p === p.toUpperCase() ? 'color.r' : 'color.b'), name: PIECE_EN[p.toUpperCase()] });
    return t('piece.full', { color: t(p === p.toUpperCase() ? 'color.r' : 'color.b'), name: names[p] });
  }

  function apply(root) {
    (root || document).querySelectorAll('[data-i18n]').forEach(function (el) {
      el.textContent = t(el.getAttribute('data-i18n'));
    });
    (root || document).querySelectorAll('[data-i18n-attr]').forEach(function (el) {
      el.getAttribute('data-i18n-attr').split(';').forEach(function (pair) {
        var kv = pair.split(':');
        if (kv.length === 2) el.setAttribute(kv[0].trim(), t(kv[1].trim()));
      });
    });
  }

  function setLang(l) {
    lang = l === 'en' ? 'en' : 'zh-TW';
    var o = readSettings();
    o.lang = lang;
    try { localStorage.setItem(SKEY, JSON.stringify(o)); } catch (e) { /* 不存 */ }
  }

  window.I18N = {
    DICT: DICT,
    t: t,
    apply: apply,
    pieceName: pieceName,
    has: function (key) { return Object.prototype.hasOwnProperty.call(DICT['zh-TW'], key); },
    getLang: function () { return lang; },
    setLang: setLang
  };
